import os
import json
import torch
import numpy as np
import pickle
from app.ml_services.anomaly_detection.models import LSTMAutoencoder

MODEL_DIR = "app/ml_services/anomaly_detection/models"

class AnomalyDetectionService:
    def __init__(self):
        self.model_type = None
        self.model = None
        self.scaler = None
        self.features = []
        self.threshold = 0.0
        self.is_loaded = False
        self.load_model()

    def load_model(self):
        config_path = os.path.join(MODEL_DIR, "model_config.json")
        scaler_path = os.path.join(MODEL_DIR, "scaler.pkl")
        
        if not os.path.exists(config_path) or not os.path.exists(scaler_path):
            return # Model not trained yet
            
        with open(config_path, "r") as f:
            config = json.load(f)
            
        with open(scaler_path, "rb") as f:
            self.scaler = pickle.load(f)
            
        self.model_type = config.get("type")
        self.features = config.get("features", [])
        
        if self.model_type == "lstm":
            self.threshold = config.get("threshold", 0.0)
            # 6 features generated by preprocessing
            self.model = LSTMAutoencoder(n_features=6)
            self.model.load_state_dict(torch.load(os.path.join(MODEL_DIR, "best_model.pt")))
            self.model.eval()
        else:
            with open(os.path.join(MODEL_DIR, "best_model.pkl"), "rb") as f:
                self.model = pickle.load(f)
                
        self.is_loaded = True

    def _preprocess(self, data: dict) -> np.ndarray:
        # Expects: value, sin_hour, cos_hour, rolling_mean_5, rolling_std_5, lag_1
        arr = np.array([[
            data.get("value", 0.0),
            data.get("sin_hour", 0.0),
            data.get("cos_hour", 1.0),
            data.get("rolling_mean_5", data.get("value", 0.0)),
            data.get("rolling_std_5", 0.0),
            data.get("lag_1", data.get("value", 0.0))
        ]])
        return self.scaler.transform(arr)

    def predict(self, data: dict) -> bool:
        if not self.is_loaded:
            raise ValueError("Model is not loaded.")
            
        x_scaled = self._preprocess(data)
        
        if self.model_type == "lstm":
            # LSTM expects (batch, seq, features)
            # For online inference we might pass just 1 step, but model was trained on seq=5.
            # We'll pad the sequence by repeating it if needed, or if data provides a history window.
            # Assuming data passed in is already a flat vector representing the current state.
            seq = np.repeat(x_scaled, 5, axis=0).reshape(1, 5, -1)
            tensor_x = torch.tensor(seq, dtype=torch.float32)
            with torch.no_grad():
                recon = self.model(tensor_x)
                mse = torch.mean(torch.pow(tensor_x - recon, 2)).item()
            return mse > self.threshold
        else:
            # Isolation forest
            pred = self.model.predict(x_scaled)
            return bool(pred[0] == -1)

anomaly_service = AnomalyDetectionService()
